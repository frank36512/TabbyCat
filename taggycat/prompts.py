def render_style(style: StylePreset, *keys: str) -> str:
    """把指定风格维度渲染成紧凑的多行风格卡（空值自动跳过）。"""
    lines: list[str] = []
    for key in keys:
        value = (getattr(style, key, "") or "").strip()
        if value:
            lines.append(f"- {_STYLE_LABELS.get(key, key)}：{value}")
    return "\n".join(lines)


def style_card(style: StylePreset, kind: str = "script") -> str:
    """按阶段渲染风格卡；未知 kind 回退到完整写作卡。"""
    keys = _CARD_KEYS.get(kind, _CARD_KEYS["script"])
    return render_style(style, *keys)


def style_sample(style: StylePreset) -> str:
    """风格示例句（作为 few-shot 注入文案提示词）。"""
    return f"（范例，学习其语气与句式，勿照抄内容）{style.sample}"


# ---------------------------------------------------------------------
# 语速：每种风格的基准语速同步驱动「文案字数预算」与「edge 配音语速」
# ---------------------------------------------------------------------
DEFAULT_SPEECH_RATE = 4.5  # 中文口播基准语速（字/秒），对应 edge rate "+0%"


def style_rate(style: StylePreset) -> float:
    """风格的文案基准语速（字/秒）；异常值回退到全局基准。"""
    return style.rate if style.rate and style.rate > 0 else DEFAULT_SPEECH_RATE


def style_edge_rate(style: StylePreset) -> str:
    """把风格语速换算成 edge-tts 的 rate 字符串（基准 4.5 字/秒 = +0%）。"""
    pct = round((style_rate(style) / DEFAULT_SPEECH_RATE - 1) * 100)
    pct = max(-50, min(100, pct))
    return f"{pct:+d}%"


def resolve_edge_rate(
    style: StylePreset, configured: str = "", override: str = ""
) -> str:
    """解析任务实际使用的 edge 语速。

    优先级：任务级覆盖 override > 用户自定义的全局 rate（非 +0%）> 风格语速。
    """
    if override and override.strip():
        return override.strip()
    cfg = (configured or "").strip()
    if cfg and cfg not in ("+0%", "0%"):
        return cfg
    return style_edge_rate(style)


def script_rate(style: StylePreset, engine: str = "edge") -> float:
    """文案字数预算采用的语速。

    edge 引擎可精确控制语速，用风格语速；其他引擎语速不可控，回退基准语速，
    以免文案字数与实际配音时长脱节（配音过长会撑长片段、引发画面定格）。
    """
    if (engine or "edge").lower() == "edge":
        return style_rate(style)
    return DEFAULT_SPEECH_RATE


def style_hooks(style: StylePreset) -> str:
    """开场钩子模板库（供文案首段套用）。"""
    return "\n".join(f"- {h}" for h in style.hooks if h.strip())


def style_endings(style: StylePreset) -> str:
    """结尾模板库（供文案末段套用）。"""
    return "\n".join(f"- {e}" for e in style.endings if e.strip())


def pov_line(style: StylePreset, mode: str = "", character: str = "") -> str:
    """叙述视角指令；mode 为空时回退到风格自带视角。

    - 第一人称：以指定角色（或主角）的视角用「我」讲述，更沉浸；
    - 第三人称：保持客观旁白；
    - 空/auto：使用风格预设的 pov。
    """
    mode = (mode or "").strip().lower()
    character = (character or "").strip()
    if mode in ("first", "第一人称", "第一人称视角"):
        who = f"「{character}」" if character else "主角"
        return (
            f"必须用第一人称（我）代入{who}讲述：以他的所见所感出发，"
            "可以透露他的心理活动，但不得编造画面中没有的情节；"
            "全片人称保持一致，不要中途跳回第三人称。"
        )
    if mode in ("third", "第三人称", "第三人称视角"):
        return "保持第三人称客观旁白视角，不代入角色内心，不出现「我」指代角色。"
    return style.pov


